// Generates firmware/LiftIQ_BLE/protocol_v1_selftest_vectors.h from the golden vectors, so the
// board's boot self-test (DEBUG_PROTOCOL_SELFTEST) uses exactly the contract inputs.
//   node tests/compat/tools/gen-selftest-header.mjs          (rewrite the header)
// tests/compat/golden.test.js fails when the checked-in header is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const GOLDEN_PATH = resolve(here, "../golden/v1_vectors.json");
export const HEADER_PATH = resolve(here, "../../../firmware/LiftIQ_BLE/protocol_v1_selftest_vectors.h");

function cfloat(value) {
  const text = String(value);
  return `${/[.eE]/.test(text) ? text : `${text}.0`}f`;
}

export function buildSelftestHeader(golden) {
  const rows = golden.telemetryV1.map((v) => {
    const i = v.input;
    return `  { "${v.name}", { ${cfloat(i.ax)}, ${cfloat(i.ay)}, ${cfloat(i.az)}, ${cfloat(i.totalAccel)}, ${cfloat(i.dynamicAccel)}, ` +
      `${i.seq}, ${i.phase}, ${i.calibrationStatus}, ${i.repCount}, ${i.batteryMillivolts} } },`;
  });
  return [
    "// GENERATED by tests/compat/tools/gen-selftest-header.mjs from tests/compat/golden/v1_vectors.json.",
    "// Do not edit by hand. Used only when DEBUG_PROTOCOL_SELFTEST is 1.",
    "#ifndef LIFTIQ_PROTOCOL_V1_SELFTEST_VECTORS_H",
    "#define LIFTIQ_PROTOCOL_V1_SELFTEST_VECTORS_H",
    "",
    '#include "protocol_v1.h"',
    "",
    "struct ProtocolSelftestVector {",
    "  const char *name;",
    "  TelemetryV1 input;",
    "};",
    "",
    "static const ProtocolSelftestVector PROTOCOL_SELFTEST_VECTORS[] = {",
    ...rows,
    "};",
    "static const size_t PROTOCOL_SELFTEST_COUNT = sizeof(PROTOCOL_SELFTEST_VECTORS) / sizeof(PROTOCOL_SELFTEST_VECTORS[0]);",
    "",
    "#endif  // LIFTIQ_PROTOCOL_V1_SELFTEST_VECTORS_H",
    "",
  ].join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const golden = JSON.parse(readFileSync(GOLDEN_PATH, "utf8"));
  writeFileSync(HEADER_PATH, buildSelftestHeader(golden));
  console.log(`wrote ${HEADER_PATH}`);
}
